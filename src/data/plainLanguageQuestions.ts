export function applyPlainLanguageOverride(question: Question): Question {
  const override = plainLanguageOverrides[question.id]
  if (!override) return question

  return {
    ...question,
    ...override,
    version: Math.max(question.version ?? 1, 2),
  }
}

export function getPlainLanguageGuide(question: Question): string | undefined {
  return plainLanguageGuides[question.id]
}
