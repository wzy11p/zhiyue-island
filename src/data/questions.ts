const questionMetadataById: Record<string, QuestionMetadataSeed> = questionMetadata
const baseQuestionIds = new Set(baseQuestions.map((question) => question.id))
const metadataIds = Object.keys(questionMetadataById)
const extraMetadataIds = metadataIds.filter((id) => !baseQuestionIds.has(id))

if (metadataIds.length !== baseQuestions.length || extraMetadataIds.length > 0) {
  throw new Error(
    `Question metadata mismatch: ${metadataIds.length}/${baseQuestions.length}; extra=${extraMetadataIds.join(',')}`,
  )
}

export const questions: Question[] = baseQuestions.map((question) => {
  const metadata = questionMetadataById[question.id]
  if (!metadata) throw new Error(`Missing question metadata: ${question.id}`)

  const wrongOptionIndexes = question.options
    .map((_, index) => index)
    .filter((index) => index !== question.correctIndex)
  const mappedWrongIndexes = Object.keys(metadata.reasons).map(Number).sort((a, b) => a - b)

  if (
    mappedWrongIndexes.length !== wrongOptionIndexes.length
    || mappedWrongIndexes.some((index, position) => index !== wrongOptionIndexes[position])
  ) {
    throw new Error(`Misconception map does not match wrong options: ${question.id}`)
  }

  const sourceRefs = conceptSourceRefs[metadata.conceptId]
  if (!sourceRefs.length) throw new Error(`Missing concept sources: ${metadata.conceptId}`)

  return {
    ...question,
    conceptId: metadata.conceptId,
    stage: metadata.stage,
    format: 'single-choice',
    objectiveId: `${metadata.conceptId}:${metadata.objectiveSuffix}`,
    misconceptionMap: metadata.reasons,
    sourceRefs,
    version: 1,
    status: 'published',
  }
})
